function IED7_Cox_IT_RT_BR_postIED_by_brain_area_IEDtime_permutation


%
% Author: Nill

clear;
clc;
close all;

%% Paths
% this was done on veronica's computer
inputFolderName_LFPIED = ...
    'D:\Nill\data\0_0_new_IED_new_area_labels\IED1_find_number_of_IEDs\';

outputFolderName = ...
    'D:\Nill\code\BART\0_0_new_IED_new_area_labels\IED7_Cox_IT_RT_BR_postIED_by_brain_area\';

if ~exist(outputFolderName, 'dir')
    mkdir(outputFolderName);
end

%% Shared settings

% Outcome-specific post-IED windows: 1000 ms for all outcomes.
settings.postIEDWindowMillisecondsRT = 500;
settings.postIEDWindowMillisecondsIT = 1000;
settings.postIEDWindowMillisecondsBR = 1000;

% FDR family: IT, RT, BR (bank), and PR (pop), within each area.
settings.fdrAlphaAcrossOutcomes = 0.05;

settings.maximumRTSeconds = 20;
settings.defaultSamplingFrequencyHz = 1000;
settings.combineLeftAndRight = true;
settings.includeUnknownArea = false;

% Sparse-area safeguards
settings.minimumParticipantsWithCoverage = 10;
settings.minimumParticipantsWithIED = 1;
settings.minimumIEDsInArea = 1;
settings.minimumEndpointEventsInsideWindow = 1;
settings.minimumEndpointEventsOutsideWindow = 1;

% Within-trial IED-time permutation settings
settings.numberOfPermutations = 1000;
settings.minimumValidPermutations = 800;
settings.permutationRandomSeed = 1;
rng(settings.permutationRandomSeed, 'twister');

% Figure colors
colorRT = [0.204  0.459  0.702];   % blue
colorIT = [0.847  0.333  0.153];   % orange
colorBR = [0.250  0.600  0.250];   % green
colorPop = [0.494  0.184  0.556];  % purple
markerAlpha = 0.5;

%% Run IT, RT, and BR analyses

[ITResults, ~] = runBrainAreaAnalysis( ...
    inputFolderName_LFPIED, "IT", settings);

[RTResults, ~] = runBrainAreaAnalysis( ...
    inputFolderName_LFPIED, "RT", settings);

[BRResults, ~] = runBrainAreaAnalysis( ...
    inputFolderName_LFPIED, "BR", settings);

%% BH-FDR correction across IT, RT, BR, and PR within each area

[ITResults, RTResults, BRResults] = ...
    applyFDRWithinAreaAcrossOutcomes( ...
        ITResults, RTResults, BRResults, ...
        settings.fdrAlphaAcrossOutcomes);

saveCorrectedAreaCSV(outputFolderName, "IT", ITResults);
saveCorrectedAreaCSV(outputFolderName, "RT", RTResults);
saveCorrectedAreaCSV(outputFolderName, "BR", BRResults);

%% Save IT, RT, and BR forest-plot PDFs

itFigureOutputFile = fullfile(outputFolderName, ...
    'IT_brain_area_cox_forest_plot.pdf');

rtFigureOutputFile = fullfile(outputFolderName, ...
    'RT_brain_area_cox_forest_plot.pdf');

brFigureOutputFile = fullfile(outputFolderName, ...
    'BR_bank_pop_brain_area_cox_forest_plot.pdf');

plotSeparateAreaForestPlots( ...
    ITResults, RTResults, BRResults, ...
    colorIT, colorRT, colorBR, colorPop, markerAlpha, ...
    settings, ...
    itFigureOutputFile, ...
    rtFigureOutputFile, ...
    brFigureOutputFile);

fprintf('\n============================================================\n');
fprintf('All three analyses finished.\n');
fprintf('Post-IED windows: IT = %d ms, RT = %d ms, BR = %d ms.\n', ...
    settings.postIEDWindowMillisecondsIT, ...
    settings.postIEDWindowMillisecondsRT, ...
    settings.postIEDWindowMillisecondsBR);
fprintf('Permutation test: %d within-trial circular IED shifts.\n', ...
    settings.numberOfPermutations);
fprintf('Saved the three corrected CSV files and three forest-plot PDFs.\n');

end

%% Local functions

function [areaResults, areaModels] = runBrainAreaAnalysis( ...
    inputFolderName_LFPIED, analysisType, settings)

    analysisPrefix = analysisType;

    % Select the post-IED window for the current behavioral outcome.
    switch analysisType
        case "RT"
            postIEDWindowMilliseconds = ...
                settings.postIEDWindowMillisecondsRT;
        case "IT"
            postIEDWindowMilliseconds = ...
                settings.postIEDWindowMillisecondsIT;
        case "BR"
            postIEDWindowMilliseconds = ...
                settings.postIEDWindowMillisecondsBR;
        otherwise
            error('Unknown analysis type: %s', analysisType);
    end

    postIEDWindowSeconds = postIEDWindowMilliseconds / 1000;

    maximumRTSeconds = settings.maximumRTSeconds;
    defaultSamplingFrequencyHz = settings.defaultSamplingFrequencyHz;
    combineLeftAndRight = settings.combineLeftAndRight;
    includeUnknownArea = settings.includeUnknownArea;
    minimumParticipantsWithCoverage = ...
        settings.minimumParticipantsWithCoverage;
    minimumParticipantsWithIED = settings.minimumParticipantsWithIED;
    minimumIEDsInArea = settings.minimumIEDsInArea;
    minimumEndpointEventsInsideWindow = ...
        settings.minimumEndpointEventsInsideWindow;
    minimumEndpointEventsOutsideWindow = ...
        settings.minimumEndpointEventsOutsideWindow;

    fileList = dir(fullfile(inputFolderName_LFPIED, '*.LFPIED.mat'));

    if isempty(fileList)
        error('No .LFPIED.mat files were found.');
    end

    participants = struct( ...
        'patientID', {}, ...
        'RTs', {}, ...
        'ITs', {}, ...
        'BankedTrials', {}, ...
        'isControl', {}, ...
        'balloonColorCode', {}, ...
        'validTrials', {}, ...
        'durationSeconds', {}, ...
        'finalEventObserved', {}, ...
        'IEDoccurrence', {}, ...
        'samplingFrequencyHz', {}, ...
        'selectedAreaLabels', {});

    allAreas = strings(0, 1);

    %% Load and organize participant data

    for pt = 1:length(fileList)

        fileName = fileList(pt).name;
        fileNameParts = strsplit(fileName, '.');
        patientID = string(fileNameParts{1});

        fprintf('\nLoading patient for %s: %s\n', ...
            analysisPrefix, patientID);

        loadedData = load(fullfile(inputFolderName_LFPIED, fileName));

        if ~isfield(loadedData, 'LFPIED')
            fprintf('Skipped: LFPIED structure was not found.\n');
            continue;
        end

        LFPIED = loadedData.LFPIED;

        switch analysisType
            case "IT"
                requiredFields = { ...
                    'selectedChans', 'anatomicalLocs', 'RTs', 'ITs', ...
                    'isControl', 'balloonType', 'IED_occurance_IT'};
            case "RT"
                requiredFields = { ...
                    'selectedChans', 'anatomicalLocs', 'RTs', ...
                    'isControl', 'balloonType', 'IED_occurance_RT'};
            case "BR"
                requiredFields = { ...
                    'selectedChans', 'anatomicalLocs', 'RTs', 'ITs', ...
                    'BankedTrials', 'isControl', 'balloonType', ...
                    'IED_occurance_IT'};
            otherwise
                error('Unknown analysis type: %s', analysisType);
        end

        missingField = false;

        for ff = 1:length(requiredFields)
            if ~isfield(LFPIED, requiredFields{ff})
                fprintf('Skipped: missing field %s.\n', ...
                    requiredFields{ff});
                missingField = true;
            end
        end

        if missingField
            continue;
        end

        selectedChans = round(LFPIED.selectedChans(:));
        nSelectedChannels = length(selectedChans);

        if nSelectedChannels == 0
            fprintf('Skipped: no selected channels.\n');
            continue;
        end

        selectedAreaLabels = getSelectedChannelLabels( ...
            LFPIED.anatomicalLocs, selectedChans, nSelectedChannels);

        selectedAreaLabels = cleanAreaLabels( ...
            selectedAreaLabels, combineLeftAndRight);

        % Exclude all NaC/nucleus accumbens, white-matter, and lateral-ventricle channels.
        excludedAreaRows = isExcludedAreaLabel(selectedAreaLabels);
        selectedAreaLabels(excludedAreaRows) = "Excluded";

        RTs = double(LFPIED.RTs(:));
        isControl = double(LFPIED.isControl(:));
        balloonType = double(LFPIED.balloonType(:));

        switch analysisType
            case "RT"
                ITs = NaN(size(RTs));
                BankedTrials = NaN(size(RTs));
                vectorLengths = [ ...
                    length(RTs), length(isControl), length(balloonType)];
            case "IT"
                ITs = double(LFPIED.ITs(:));
                BankedTrials = NaN(size(RTs));
                vectorLengths = [ ...
                    length(RTs), length(ITs), ...
                    length(isControl), length(balloonType)];
            case "BR"
                ITs = double(LFPIED.ITs(:));
                BankedTrials = double(LFPIED.BankedTrials(:));
                vectorLengths = [ ...
                    length(RTs), length(ITs), length(BankedTrials), ...
                    length(isControl), length(balloonType)];
        end

        if isfield(LFPIED, 'nTrials') && ...
                isscalar(LFPIED.nTrials) && isfinite(LFPIED.nTrials)
            vectorLengths(end + 1) = LFPIED.nTrials;
        end

        nTrials = floor(min(vectorLengths));

        RTs = RTs(1:nTrials);
        isControl = isControl(1:nTrials);
        balloonType = balloonType(1:nTrials);
        balloonColorCode = mapBalloonColorCode(balloonType);
        ITs = ITs(1:nTrials);
        BankedTrials = BankedTrials(1:nTrials);

        switch analysisType
            case "RT"
                durationSeconds = RTs;
                finalEventObserved = true(nTrials, 1);
                IEDoccurrence = LFPIED.IED_occurance_RT;
            case "IT"
                durationSeconds = ITs;
                finalEventObserved = true(nTrials, 1);
                IEDoccurrence = LFPIED.IED_occurance_IT;
            case "BR"
                durationSeconds = ITs;
                finalEventObserved = BankedTrials == 1;
                IEDoccurrence = LFPIED.IED_occurance_IT;
        end

        validTrials = ...
            isControl == 0 & ...
            isfinite(RTs) & ...
            RTs > 0 & ...
            RTs <= maximumRTSeconds & ...
            isfinite(durationSeconds) & ...
            durationSeconds > 0 & ...
            isfinite(balloonColorCode) & ...
            ismember(balloonColorCode, [1 2 3]);

        if analysisType == "BR"
            validTrials = validTrials & ...
                isfinite(BankedTrials) & ...
                ismember(BankedTrials, [0 1]);
        end

        samplingFrequencyHz = getSamplingFrequency( ...
            LFPIED, defaultSamplingFrequencyHz);

        newParticipant.patientID = patientID;
        newParticipant.RTs = RTs;
        newParticipant.ITs = ITs;
        newParticipant.BankedTrials = BankedTrials;
        newParticipant.isControl = isControl;
        newParticipant.balloonColorCode = balloonColorCode;
        newParticipant.validTrials = validTrials;
        newParticipant.durationSeconds = durationSeconds;
        newParticipant.finalEventObserved = finalEventObserved;
        newParticipant.IEDoccurrence = IEDoccurrence;
        newParticipant.samplingFrequencyHz = samplingFrequencyHz;
        newParticipant.selectedAreaLabels = selectedAreaLabels;

        participants(end + 1) = newParticipant; 

        participantAreas = unique(selectedAreaLabels, 'stable');

        if ~includeUnknownArea
            participantAreas = participantAreas( ...
                participantAreas ~= "Unknown");
        end

        participantAreas = participantAreas( ...
            participantAreas ~= "Excluded");

        allAreas = unique([allAreas; participantAreas], 'stable');

    end

    if isempty(participants)
        error('No valid participant data were loaded for %s.', ...
            analysisPrefix);
    end

    % Hard safety filter before any model is fitted.
    allAreas = allAreas(~isExcludedAreaLabel(allAreas));

    if isempty(allAreas)
        error(['No anatomical areas were found after excluding NaC, ' ...
            'white matter, and lateral ventricle.']);
    end

    fprintf('\n============================================================\n');
    fprintf('%s area-specific %d-ms post-IED Cox analysis\n', ...
        analysisPrefix, postIEDWindowMilliseconds);
    fprintf('============================================================\n');
    fprintf('Loaded participants: %d\n', length(participants));
    fprintf('Anatomical areas: %d\n', length(allAreas));

    %% Fit one Cox model per anatomical area

    areaResults = initializeAreaResultsTable();
    areaModels = struct();

    for aa = 1:length(allAreas)

        anatomicalArea = allAreas(aa);

        fprintf('\n------------------------------------------------------------\n');
        fprintf('Area %d/%d: %s\n', ...
            aa, length(allAreas), anatomicalArea);

        countingProcessData = emptyCountingProcessTable();

        nParticipantsWithCoverage = 0;
        nParticipantsWithIED = 0;
        nIEDsInArea = 0;
        nValidTrials = 0;

        for pt = 1:length(participants)

            P = participants(pt);
            areaLocalChannels = find( ...
                P.selectedAreaLabels == anatomicalArea);

            if isempty(areaLocalChannels)
                continue;
            end

            nParticipantsWithCoverage = ...
                nParticipantsWithCoverage + 1;

            areaIEDoccurrence = filterIEDsToArea( ...
                P.IEDoccurrence, areaLocalChannels);

            validAreaIEDRows = getValidAreaIEDRows( ...
                areaIEDoccurrence, P.validTrials);

            thisParticipantIEDCount = sum(validAreaIEDRows);
            nIEDsInArea = nIEDsInArea + thisParticipantIEDCount;

            if thisParticipantIEDCount > 0
                nParticipantsWithIED = nParticipantsWithIED + 1;
            end

            validTrialNumbers = find(P.validTrials);
            nValidTrials = nValidTrials + length(validTrialNumbers);

            for tt = 1:length(validTrialNumbers)

                trialNumber = validTrialNumbers(tt);

                if analysisType == "BR"

                    % The same trial is represented in two transition
                    % strata inside one Cox fit. A banked trial is an
                    % observed bank event and a censored pop event. A
                    % popped trial is the reverse.
                    bankObserved = P.BankedTrials(trialNumber) == 1;
                    popObserved = P.BankedTrials(trialNumber) == 0;

                    bankRows = makePostIEDWindowRows( ...
                        P.patientID, ...
                        trialNumber, ...
                        P.durationSeconds(trialNumber), ...
                        areaIEDoccurrence, ...
                        P.samplingFrequencyHz, ...
                        P.balloonColorCode(trialNumber), ...
                        bankObserved, ...
                        postIEDWindowSeconds, ...
                        "bank");

                    popRows = makePostIEDWindowRows( ...
                        P.patientID, ...
                        trialNumber, ...
                        P.durationSeconds(trialNumber), ...
                        areaIEDoccurrence, ...
                        P.samplingFrequencyHz, ...
                        P.balloonColorCode(trialNumber), ...
                        popObserved, ...
                        postIEDWindowSeconds, ...
                        "pop");

                    trialRows = [bankRows; popRows];

                else

                    trialRows = makePostIEDWindowRows( ...
                        P.patientID, ...
                        trialNumber, ...
                        P.durationSeconds(trialNumber), ...
                        areaIEDoccurrence, ...
                        P.samplingFrequencyHz, ...
                        P.balloonColorCode(trialNumber), ...
                        P.finalEventObserved(trialNumber), ...
                        postIEDWindowSeconds, ...
                        "single");

                end

                countingProcessData = ...
                    [countingProcessData; trialRows]; 

            end

        end

        status = "fitted";

        if nParticipantsWithCoverage < minimumParticipantsWithCoverage
            status = "skipped: insufficient participants with coverage";
        elseif nParticipantsWithIED < minimumParticipantsWithIED
            status = "skipped: no participants with area IEDs";
        elseif nIEDsInArea < minimumIEDsInArea
            status = "skipped: insufficient area IEDs";
        elseif isempty(countingProcessData)
            status = "skipped: no counting-process rows";
        end

        nCountingRows = height(countingProcessData);
        nEndpointEvents = 0;
        nEventsInsideWindow = 0;
        nEventsOutsideWindow = 0;
        timeInsideWindowSeconds = 0;
        timeOutsideWindowSeconds = 0;
        nBankEvents = 0;
        nPopEvents = 0;
        nBankEventsOutsideWindow = 0;
        nBankEventsInsideWindow = 0;
        nPopEventsOutsideWindow = 0;
        nPopEventsInsideWindow = 0;

        betaPrimary = NaN;
        robustSEPrimary = NaN;
        robustZPrimary = NaN;
        pValuePrimary = NaN;
        permutationPValuePrimary = NaN;
        nValidPermutationsPrimary = 0;
        betaCILow = NaN;
        betaCIHigh = NaN;
        hazardRatio = NaN;
        hazardRatioCILow = NaN;
        hazardRatioCIHigh = NaN;

        betaPop = NaN;
        robustSEPop = NaN;
        robustZPop = NaN;
        pValuePop = NaN;
        permutationPValuePop = NaN;
        nValidPermutationsPop = 0;
        betaPopCILow = NaN;
        betaPopCIHigh = NaN;
        hazardRatioPop = NaN;
        hazardRatioPopCILow = NaN;
        hazardRatioPopCIHigh = NaN;

        betaBankMinusPop = NaN;
        robustSEBankMinusPop = NaN;
        robustZBankMinusPop = NaN;
        pValueBankVsPop = NaN;
        permutationPValueBankVsPop = NaN;
        nValidPermutationsBankVsPop = 0;
        betaBankMinusPopCILow = NaN;
        betaBankMinusPopCIHigh = NaN;

        logLikelihood = NaN;
        nModelParticipants = 0;
        referenceBalloonColor = "";

        if status == "fitted"

            [countingProcessData.patientStratum, patientLevels] = ...
                findgroups(countingProcessData.patientID);

            if analysisType == "BR"
                % Separate baseline hazards for every participant and for
                % each transition, while keeping one combined model.
                strata = findgroups( ...
                    countingProcessData.patientID, ...
                    countingProcessData.transitionType);
            else
                strata = countingProcessData.patientStratum;
            end

            [X, predictorNames, referenceBalloonColor] = ...
                buildPredictorMatrix(countingProcessData, analysisType);

            T = [countingProcessData.tStart, ...
                countingProcessData.tStop];
            censoring = logical(countingProcessData.censored);

            validRows = ...
                all(isfinite(X), 2) & ...
                all(isfinite(T), 2) & ...
                T(:, 1) >= 0 & ...
                T(:, 2) > T(:, 1) & ...
                isfinite(strata);

            X = X(validRows, :);
            T = T(validRows, :);
            censoring = censoring(validRows);
            strata = strata(validRows);
            countingProcessData = countingProcessData(validRows, :);

            nCountingRows = height(countingProcessData);
            nModelParticipants = ...
                length(unique(countingProcessData.patientID));
            nEndpointEvents = sum( ...
                countingProcessData.eventAtStop == 1);

            nEventsOutsideWindow = sum( ...
                countingProcessData.eventAtStop == 1 & ...
                countingProcessData.postIED == 0);

            nEventsInsideWindow = sum( ...
                countingProcessData.eventAtStop == 1 & ...
                countingProcessData.postIED == 1);

            if analysisType == "BR"
                bankTransition = ...
                    countingProcessData.transitionType == "bank";
                popTransition = ...
                    countingProcessData.transitionType == "pop";

                nBankEvents = sum( ...
                    countingProcessData.eventAtStop == 1 & ...
                    bankTransition);
                nPopEvents = sum( ...
                    countingProcessData.eventAtStop == 1 & ...
                    popTransition);

                nBankEventsOutsideWindow = sum( ...
                    countingProcessData.eventAtStop == 1 & ...
                    bankTransition & ...
                    countingProcessData.postIED == 0);
                nBankEventsInsideWindow = sum( ...
                    countingProcessData.eventAtStop == 1 & ...
                    bankTransition & ...
                    countingProcessData.postIED == 1);

                nPopEventsOutsideWindow = sum( ...
                    countingProcessData.eventAtStop == 1 & ...
                    popTransition & ...
                    countingProcessData.postIED == 0);
                nPopEventsInsideWindow = sum( ...
                    countingProcessData.eventAtStop == 1 & ...
                    popTransition & ...
                    countingProcessData.postIED == 1);
            end

            timeOutsideWindowSeconds = sum( ...
                (countingProcessData.tStop - ...
                 countingProcessData.tStart) .* ...
                (countingProcessData.postIED == 0), ...
                'omitnan');

            timeInsideWindowSeconds = sum( ...
                (countingProcessData.tStop - ...
                 countingProcessData.tStart) .* ...
                (countingProcessData.postIED == 1), ...
                'omitnan');

            if nModelParticipants < minimumParticipantsWithCoverage
                status = "skipped: insufficient model participants";
            elseif timeInsideWindowSeconds <= 0
                status = "skipped: no area-specific exposed time";
            elseif nEventsInsideWindow < ...
                    minimumEndpointEventsInsideWindow
                status = "skipped: no endpoint events inside area-specific windows";
            elseif nEventsOutsideWindow < ...
                    minimumEndpointEventsOutsideWindow
                status = "skipped: no endpoint events outside area-specific windows";
            elseif analysisType == "BR" && ...
                    nBankEventsInsideWindow < ...
                    minimumEndpointEventsInsideWindow
                status = "skipped: no bank events inside area-specific windows";
            elseif analysisType == "BR" && ...
                    nBankEventsOutsideWindow < ...
                    minimumEndpointEventsOutsideWindow
                status = "skipped: no bank events outside area-specific windows";
            elseif analysisType == "BR" && ...
                    nPopEventsInsideWindow < ...
                    minimumEndpointEventsInsideWindow
                status = "skipped: no pop events inside area-specific windows";
            elseif analysisType == "BR" && ...
                    nPopEventsOutsideWindow < ...
                    minimumEndpointEventsOutsideWindow
                status = "skipped: no pop events outside area-specific windows";
            elseif size(X, 1) <= size(X, 2)
                status = "skipped: insufficient rows for predictor matrix";
            end

        end

        if status == "fitted"

            try
                coxOptions = statset('coxphfit');
                coxOptions.Display = 'off';
                coxOptions.MaxIter = 1000;
                coxOptions.MaxFunEvals = 5000;

                [beta, logLikelihood, ...
                    baselineCumulativeHazard, stats] = coxphfit( ...
                        X, ...
                        T, ...
                        'Censoring', censoring, ...
                        'Strata', strata, ...
                        'Ties', 'efron', ...
                        'Baseline', 0, ...
                        'Options', coxOptions);

                [clusterRobustCovariance, clusterRobustSE, ...
                    clusterRobustZ, clusterRobustP] = ...
                    computeClusterRobustInference( ...
                        stats, beta, ...
                        countingProcessData.patientStratum);

                betaPrimary = beta(1);
                robustSEPrimary = clusterRobustSE(1);
                robustZPrimary = clusterRobustZ(1);
                pValuePrimary = clusterRobustP(1);

                betaCILow = betaPrimary - 1.96 * robustSEPrimary;
                betaCIHigh = betaPrimary + 1.96 * robustSEPrimary;

                hazardRatio = exp(betaPrimary);
                hazardRatioCILow = exp(betaCILow);
                hazardRatioCIHigh = exp(betaCIHigh);

                if analysisType == "BR"
                    % Predictor 1 is the IED effect on bank hazard.
                    % Predictor 2 is the IED effect on pop hazard.
                    betaPop = beta(2);
                    robustSEPop = clusterRobustSE(2);
                    robustZPop = clusterRobustZ(2);
                    pValuePop = clusterRobustP(2);

                    betaPopCILow = ...
                        betaPop - 1.96 * robustSEPop;
                    betaPopCIHigh = ...
                        betaPop + 1.96 * robustSEPop;

                    hazardRatioPop = exp(betaPop);
                    hazardRatioPopCILow = exp(betaPopCILow);
                    hazardRatioPopCIHigh = exp(betaPopCIHigh);

                    % Direct test of whether the bank and pop IED
                    % coefficients are different in this one model.
                    betaBankMinusPop = betaPrimary - betaPop;
                    varianceBankMinusPop = ...
                        clusterRobustCovariance(1, 1) + ...
                        clusterRobustCovariance(2, 2) - ...
                        2 * clusterRobustCovariance(1, 2);

                    robustSEBankMinusPop = sqrt( ...
                        max(varianceBankMinusPop, 0));

                    if robustSEBankMinusPop > 0 && ...
                            isfinite(robustSEBankMinusPop)
                        robustZBankMinusPop = ...
                            betaBankMinusPop / robustSEBankMinusPop;
                        pValueBankVsPop = 2 * normcdf( ...
                            -abs(robustZBankMinusPop), 0, 1);
                        betaBankMinusPopCILow = ...
                            betaBankMinusPop - ...
                            1.96 * robustSEBankMinusPop;
                        betaBankMinusPopCIHigh = ...
                            betaBankMinusPop + ...
                            1.96 * robustSEBankMinusPop;
                    end
                end

                safeAreaNameBase = ...
                    matlab.lang.makeValidName(char(anatomicalArea));
                safeAreaName = safeAreaNameBase;
                duplicateNumber = 1;

                while isfield(areaModels, safeAreaName)
                    duplicateNumber = duplicateNumber + 1;
                    safeAreaName = sprintf('%s_%d', ...
                        safeAreaNameBase, duplicateNumber);
                end

                areaModels.(safeAreaName) = struct( ...
                    'anatomicalArea', anatomicalArea, ...
                    'beta', beta, ...
                    'predictorNames', predictorNames, ...
                    'logLikelihood', logLikelihood, ...
                    'baselineCumulativeHazard', ...
                        baselineCumulativeHazard, ...
                    'stats', stats, ...
                    'clusterRobustCovariance', ...
                        clusterRobustCovariance, ...
                    'clusterRobustSE', clusterRobustSE, ...
                    'clusterRobustZ', clusterRobustZ, ...
                    'clusterRobustP', clusterRobustP, ...
                    'patientLevels', patientLevels, ...
                    'analysisType', analysisType, ...
                    'referenceBalloonColor', ...
                        referenceBalloonColor);

            catch modelError
                status = "failed: " + string(modelError.message);
            end

        end

        if status == "fitted"
            fprintf(['Running %d within-trial circular IED-time ' ...
                'permutations for %s...\n'], ...
                settings.numberOfPermutations, anatomicalArea);

            [permutationPValuePrimary, ...
             permutationPValuePop, ...
             permutationPValueBankVsPop, ...
             nValidPermutationsPrimary, ...
             nValidPermutationsPop, ...
             nValidPermutationsBankVsPop] = ...
                runAreaPermutationTest( ...
                    participants, anatomicalArea, analysisType, ...
                    postIEDWindowSeconds, settings, ...
                    robustZPrimary, robustZPop, ...
                    robustZBankMinusPop);
        end

        newRow = table( ...
            anatomicalArea, ...
            status, ...
            nParticipantsWithCoverage, ...
            nParticipantsWithIED, ...
            nModelParticipants, ...
            nValidTrials, ...
            nIEDsInArea, ...
            nCountingRows, ...
            nEndpointEvents, ...
            nEventsOutsideWindow, ...
            nEventsInsideWindow, ...
            timeOutsideWindowSeconds, ...
            timeInsideWindowSeconds, ...
            referenceBalloonColor, ...
            betaPrimary, ...
            robustSEPrimary, ...
            robustZPrimary, ...
            pValuePrimary, ...
            permutationPValuePrimary, ...
            nValidPermutationsPrimary, ...
            betaCILow, ...
            betaCIHigh, ...
            hazardRatio, ...
            hazardRatioCILow, ...
            hazardRatioCIHigh, ...
            false, ...
            nBankEvents, ...
            nPopEvents, ...
            nBankEventsOutsideWindow, ...
            nBankEventsInsideWindow, ...
            nPopEventsOutsideWindow, ...
            nPopEventsInsideWindow, ...
            betaPop, ...
            robustSEPop, ...
            robustZPop, ...
            pValuePop, ...
            permutationPValuePop, ...
            nValidPermutationsPop, ...
            betaPopCILow, ...
            betaPopCIHigh, ...
            hazardRatioPop, ...
            hazardRatioPopCILow, ...
            hazardRatioPopCIHigh, ...
            false, ...
            betaBankMinusPop, ...
            robustSEBankMinusPop, ...
            robustZBankMinusPop, ...
            pValueBankVsPop, ...
            permutationPValueBankVsPop, ...
            nValidPermutationsBankVsPop, ...
            betaBankMinusPopCILow, ...
            betaBankMinusPopCIHigh, ...
            false, ...
            'VariableNames', areaResults.Properties.VariableNames);

        areaResults = [areaResults; newRow]; 

        fprintf('Status: %s\n', status);
        fprintf('Coverage participants: %d\n', ...
            nParticipantsWithCoverage);
        fprintf('Participants with area IEDs: %d\n', ...
            nParticipantsWithIED);
        fprintf('Area IEDs: %d\n', nIEDsInArea);

        if status == "fitted"
            if analysisType == "BR"
                fprintf([ ...
                    'Bank: log(HR) = %.6f, HR = %.6f, ' ...
                    '95%% CI = [%.6f, %.6f], robust p = %.6g, ' ...
                    'permutation p = %.6g (%d valid)\n'], ...
                    betaPrimary, hazardRatio, hazardRatioCILow, ...
                    hazardRatioCIHigh, pValuePrimary, ...
                    permutationPValuePrimary, ...
                    nValidPermutationsPrimary);
                fprintf([ ...
                    'Pop:  log(HR) = %.6f, HR = %.6f, ' ...
                    '95%% CI = [%.6f, %.6f], robust p = %.6g, ' ...
                    'permutation p = %.6g (%d valid)\n'], ...
                    betaPop, hazardRatioPop, hazardRatioPopCILow, ...
                    hazardRatioPopCIHigh, pValuePop, ...
                    permutationPValuePop, nValidPermutationsPop);
                fprintf([ ...
                    'Bank minus pop log(HR) = %.6f, ' ...
                    '95%% CI = [%.6f, %.6f], robust p = %.6g, ' ...
                    'permutation p = %.6g (%d valid)\n'], ...
                    betaBankMinusPop, betaBankMinusPopCILow, ...
                    betaBankMinusPopCIHigh, pValueBankVsPop, ...
                    permutationPValueBankVsPop, ...
                    nValidPermutationsBankVsPop);
            else
                fprintf([ ...
                    'log(HR) = %.6f, HR = %.6f, ' ...
                    '95%% CI = [%.6f, %.6f], robust p = %.6g, ' ...
                    'permutation p = %.6g (%d valid)\n'], ...
                    betaPrimary, hazardRatio, hazardRatioCILow, ...
                    hazardRatioCIHigh, pValuePrimary, ...
                    permutationPValuePrimary, ...
                    nValidPermutationsPrimary);
            end
        end

    end

    %% Final hard removal of excluded labels

    excludedResultRows = ...
        isExcludedAreaLabel(areaResults.anatomicalArea);

    if any(excludedResultRows)
        fprintf([ ...
            '\nHard-removing %d NaC/white-matter/lateral-ventricle result rows ' ...
            'before saving and plotting.\n'], ...
            sum(excludedResultRows));
        areaResults(excludedResultRows, :) = [];
    end

    %% Uncorrected permutation significance

    fittedRows = areaResults.status == "fitted" & ...
        isfinite(areaResults.permutationPValue);

    if any(fittedRows)
        areaResults.significantUncorrected(fittedRows) = ...
            areaResults.permutationPValue(fittedRows) < 0.05;
    end

    if analysisType == "BR"
        fittedPopRows = areaResults.status == "fitted" & ...
            isfinite(areaResults.permutationPValuePop);
        fittedDifferenceRows = areaResults.status == "fitted" & ...
            isfinite(areaResults.permutationPValueBankVsPop);

        areaResults.significantPopUncorrected(fittedPopRows) = ...
            areaResults.permutationPValuePop(fittedPopRows) < 0.05;

        areaResults.significantBankVsPopUncorrected( ...
            fittedDifferenceRows) = ...
            areaResults.permutationPValueBankVsPop( ...
                fittedDifferenceRows) < 0.05;
    end

    areaResults = sortrows( ...
        areaResults, {'status', 'permutationPValue'}, ...
        {'ascend', 'ascend'});

end

function [permutationPValuePrimary, permutationPValuePop, ...
    permutationPValueBankVsPop, nValidPrimary, nValidPop, ...
    nValidBankVsPop] = runAreaPermutationTest( ...
        participants, anatomicalArea, analysisType, ...
        postIEDWindowSeconds, settings, observedRobustZPrimary, ...
        observedRobustZPop, observedRobustZBankMinusPop)

    numberOfPermutations = settings.numberOfPermutations;
    minimumValidPermutations = settings.minimumValidPermutations;

    permutedRobustZPrimary = NaN(numberOfPermutations, 1);
    permutedRobustZPop = NaN(numberOfPermutations, 1);
    permutedRobustZBankMinusPop = ...
        NaN(numberOfPermutations, 1);

    coxOptions = statset('coxphfit');
    coxOptions.Display = 'off';
    coxOptions.MaxIter = 1000;
    coxOptions.MaxFunEvals = 5000;

    for permutationNumber = 1:numberOfPermutations

        permutedData = buildPermutedAreaCountingProcessData( ...
            participants, anatomicalArea, analysisType, ...
            postIEDWindowSeconds);

        if isempty(permutedData)
            continue;
        end

        [permutedData.patientStratum, ~] = ...
            findgroups(permutedData.patientID);

        if analysisType == "BR"
            strata = findgroups( ...
                permutedData.patientID, ...
                permutedData.transitionType);
        else
            strata = permutedData.patientStratum;
        end

        try
            [X, ~, ~] = buildPredictorMatrix( ...
                permutedData, analysisType);
        catch
            continue;
        end

        T = [permutedData.tStart, permutedData.tStop];
        censoring = logical(permutedData.censored);

        validRows = ...
            all(isfinite(X), 2) & ...
            all(isfinite(T), 2) & ...
            T(:, 1) >= 0 & ...
            T(:, 2) > T(:, 1) & ...
            isfinite(strata);

        X = X(validRows, :);
        T = T(validRows, :);
        censoring = censoring(validRows);
        strata = strata(validRows);
        permutedData = permutedData(validRows, :);

        if isempty(X) || size(X, 1) <= size(X, 2)
            continue;
        end

        eventAtStop = permutedData.eventAtStop == 1;
        insideWindow = permutedData.postIED == 1;

        if analysisType == "BR"
            bankRows = permutedData.transitionType == "bank";
            popRows = permutedData.transitionType == "pop";

            hasRequiredEvents = ...
                any(eventAtStop & bankRows & insideWindow) && ...
                any(eventAtStop & bankRows & ~insideWindow) && ...
                any(eventAtStop & popRows & insideWindow) && ...
                any(eventAtStop & popRows & ~insideWindow);
        else
            hasRequiredEvents = ...
                any(eventAtStop & insideWindow) && ...
                any(eventAtStop & ~insideWindow);
        end

        if ~hasRequiredEvents
            continue;
        end

        try
            [betaPermutation, ~, ~, statsPermutation] = coxphfit( ...
                X, ...
                T, ...
                'Censoring', censoring, ...
                'Strata', strata, ...
                'Ties', 'efron', ...
                'Baseline', 0, ...
                'Options', coxOptions);

            [robustCovariancePermutation, ~, ...
                robustZPermutation, ~] = ...
                computeClusterRobustInference( ...
                    statsPermutation, betaPermutation, ...
                    permutedData.patientStratum);

            if ~isempty(robustZPermutation) && ...
                    isfinite(robustZPermutation(1))
                permutedRobustZPrimary(permutationNumber) = ...
                    robustZPermutation(1);
            end

            if analysisType == "BR" && ...
                    length(robustZPermutation) >= 2 && ...
                    isfinite(robustZPermutation(2))
                permutedRobustZPop(permutationNumber) = ...
                    robustZPermutation(2);

                betaDifferencePermutation = ...
                    betaPermutation(1) - betaPermutation(2);
                varianceDifferencePermutation = ...
                    robustCovariancePermutation(1, 1) + ...
                    robustCovariancePermutation(2, 2) - ...
                    2 * robustCovariancePermutation(1, 2);
                seDifferencePermutation = sqrt( ...
                    max(varianceDifferencePermutation, 0));

                if isfinite(seDifferencePermutation) && ...
                        seDifferencePermutation > 0
                    permutedRobustZBankMinusPop( ...
                        permutationNumber) = ...
                        betaDifferencePermutation / ...
                        seDifferencePermutation;
                end
            end
        catch
            % Failed permutation fits remain NaN and are not counted.
        end

        if mod(permutationNumber, 100) == 0
            fprintf('  completed %d/%d permutations\n', ...
                permutationNumber, numberOfPermutations);
        end

    end

    validPrimary = isfinite(permutedRobustZPrimary);
    validPop = isfinite(permutedRobustZPop);
    validBankVsPop = isfinite( ...
        permutedRobustZBankMinusPop);

    nValidPrimary = sum(validPrimary);
    nValidPop = sum(validPop);
    nValidBankVsPop = sum(validBankVsPop);

    permutationPValuePrimary = NaN;
    permutationPValuePop = NaN;
    permutationPValueBankVsPop = NaN;

    if isfinite(observedRobustZPrimary) && ...
            nValidPrimary >= minimumValidPermutations
        permutationPValuePrimary = ...
            (1 + sum(abs( ...
                permutedRobustZPrimary(validPrimary)) >= ...
                abs(observedRobustZPrimary))) / ...
            (nValidPrimary + 1);
    end

    if analysisType == "BR"
        if isfinite(observedRobustZPop) && ...
                nValidPop >= minimumValidPermutations
            permutationPValuePop = ...
                (1 + sum(abs( ...
                    permutedRobustZPop(validPop)) >= ...
                    abs(observedRobustZPop))) / ...
                (nValidPop + 1);
        end

        if isfinite(observedRobustZBankMinusPop) && ...
                nValidBankVsPop >= minimumValidPermutations
            permutationPValueBankVsPop = ...
                (1 + sum(abs( ...
                    permutedRobustZBankMinusPop( ...
                        validBankVsPop)) >= ...
                    abs(observedRobustZBankMinusPop))) / ...
                (nValidBankVsPop + 1);
        end
    end

end

function permutedData = buildPermutedAreaCountingProcessData( ...
    participants, anatomicalArea, analysisType, ...
    postIEDWindowSeconds)

    permutedData = emptyCountingProcessTable();

    for pt = 1:length(participants)

        P = participants(pt);
        areaLocalChannels = find( ...
            P.selectedAreaLabels == anatomicalArea);

        if isempty(areaLocalChannels)
            continue;
        end

        areaIEDoccurrence = filterIEDsToArea( ...
            P.IEDoccurrence, areaLocalChannels);

        validTrialNumbers = find(P.validTrials);

        if isempty(validTrialNumbers)
            continue;
        end

        for tt = 1:length(validTrialNumbers)

            trialNumber = validTrialNumbers(tt);
            durationSeconds = P.durationSeconds(trialNumber);

            % Apply one random circular shift to every IED timestamp in
            % this trial. This keeps the trial's IED count and the
            % temporal spacing between its IEDs unchanged.
            shiftedTrialIEDoccurrence = ...
                circularShiftIEDsWithinTrial( ...
                    areaIEDoccurrence, trialNumber, ...
                    durationSeconds, P.samplingFrequencyHz);

            if analysisType == "BR"
                bankObserved = P.BankedTrials(trialNumber) == 1;
                popObserved = P.BankedTrials(trialNumber) == 0;

                bankRows = makePostIEDWindowRows( ...
                    P.patientID, ...
                    trialNumber, ...
                    durationSeconds, ...
                    shiftedTrialIEDoccurrence, ...
                    P.samplingFrequencyHz, ...
                    P.balloonColorCode(trialNumber), ...
                    bankObserved, ...
                    postIEDWindowSeconds, ...
                    "bank");

                popRows = makePostIEDWindowRows( ...
                    P.patientID, ...
                    trialNumber, ...
                    durationSeconds, ...
                    shiftedTrialIEDoccurrence, ...
                    P.samplingFrequencyHz, ...
                    P.balloonColorCode(trialNumber), ...
                    popObserved, ...
                    postIEDWindowSeconds, ...
                    "pop");

                trialRows = [bankRows; popRows];
            else
                trialRows = makePostIEDWindowRows( ...
                    P.patientID, ...
                    trialNumber, ...
                    durationSeconds, ...
                    shiftedTrialIEDoccurrence, ...
                    P.samplingFrequencyHz, ...
                    P.balloonColorCode(trialNumber), ...
                    true, ...
                    postIEDWindowSeconds, ...
                    "single");
            end

            permutedData = [permutedData; trialRows];
        end
    end

end

function shiftedTrialIEDoccurrence = ...
    circularShiftIEDsWithinTrial( ...
        areaIEDoccurrence, trialNumber, durationSeconds, ...
        samplingFrequencyHz)

    if isempty(areaIEDoccurrence) || ...
            size(areaIEDoccurrence, 2) < 3 || ...
            ~isfinite(durationSeconds) || durationSeconds <= 0 || ...
            ~isfinite(samplingFrequencyHz) || ...
            samplingFrequencyHz <= 0
        shiftedTrialIEDoccurrence = ...
            zeros(0, size(areaIEDoccurrence, 2));
        return;
    end

    % makePostIEDWindowRows uses sample/samplingFrequencyHz and requires
    % the IED time to be strictly smaller than the trial duration.
    maximumValidSample = ...
        ceil(durationSeconds * samplingFrequencyHz) - 1;

    if maximumValidSample < 1
        shiftedTrialIEDoccurrence = ...
            zeros(0, size(areaIEDoccurrence, 2));
        return;
    end

    trialRows = ...
        isfinite(areaIEDoccurrence(:, 1)) & ...
        round(areaIEDoccurrence(:, 1)) == trialNumber & ...
        isfinite(areaIEDoccurrence(:, 3)) & ...
        areaIEDoccurrence(:, 3) >= 1 & ...
        areaIEDoccurrence(:, 3) <= maximumValidSample;

    shiftedTrialIEDoccurrence = ...
        areaIEDoccurrence(trialRows, :);

    if isempty(shiftedTrialIEDoccurrence)
        return;
    end

    % One common integer-sample shift preserves duplicate IEDs and the
    % circular spacing between all IEDs within this trial.
    shiftInSamples = randi(maximumValidSample) - 1;
    originalSamples = round( ...
        shiftedTrialIEDoccurrence(:, 3));
    shiftedSamples = mod( ...
        originalSamples - 1 + shiftInSamples, ...
        maximumValidSample) + 1;

    shiftedTrialIEDoccurrence(:, 1) = trialNumber;
    shiftedTrialIEDoccurrence(:, 3) = shiftedSamples;

end

function [ITResults, RTResults, BRResults] = ...
    applyFDRWithinAreaAcrossOutcomes( ...
        ITResults, RTResults, BRResults, fdrAlpha)

    % Correct the permutation p-values. PR is the pop coefficient from
    % the combined BR/PR competing-transition model.
    ITResults.qValueAcrossIT_RT_BR_PR = NaN(height(ITResults), 1);
    ITResults.significantFDRAcrossIT_RT_BR_PR = ...
        false(height(ITResults), 1);

    RTResults.qValueAcrossIT_RT_BR_PR = NaN(height(RTResults), 1);
    RTResults.significantFDRAcrossIT_RT_BR_PR = ...
        false(height(RTResults), 1);

    BRResults.qValueBankAcrossIT_RT_BR_PR = NaN(height(BRResults), 1);
    BRResults.significantBankFDRAcrossIT_RT_BR_PR = ...
        false(height(BRResults), 1);

    BRResults.qValuePopAcrossIT_RT_BR_PR = NaN(height(BRResults), 1);
    BRResults.significantPopFDRAcrossIT_RT_BR_PR = ...
        false(height(BRResults), 1);

    allAreas = unique([ ...
        ITResults.anatomicalArea; ...
        RTResults.anatomicalArea; ...
        BRResults.anatomicalArea], ...
        'stable');

    for aa = 1:length(allAreas)

        areaName = allAreas(aa);
        rawPValues = zeros(0, 1);
        resultSource = strings(0, 1);
        resultRow = zeros(0, 1);

        itRow = find(ITResults.anatomicalArea == areaName, 1);
        if ~isempty(itRow) && ...
                ITResults.status(itRow) == "fitted" && ...
                isfinite(ITResults.permutationPValue(itRow))
            rawPValues(end + 1, 1) = ...
                ITResults.permutationPValue(itRow);
            resultSource(end + 1, 1) = "IT";
            resultRow(end + 1, 1) = itRow;
        end

        rtRow = find(RTResults.anatomicalArea == areaName, 1);
        if ~isempty(rtRow) && ...
                RTResults.status(rtRow) == "fitted" && ...
                isfinite(RTResults.permutationPValue(rtRow))
            rawPValues(end + 1, 1) = ...
                RTResults.permutationPValue(rtRow);
            resultSource(end + 1, 1) = "RT";
            resultRow(end + 1, 1) = rtRow;
        end

        brRow = find(BRResults.anatomicalArea == areaName, 1);
        if ~isempty(brRow) && BRResults.status(brRow) == "fitted"
            if isfinite(BRResults.permutationPValue(brRow))
                rawPValues(end + 1, 1) = ...
                    BRResults.permutationPValue(brRow);
                resultSource(end + 1, 1) = "BR";
                resultRow(end + 1, 1) = brRow;
            end

            if isfinite(BRResults.permutationPValuePop(brRow))
                rawPValues(end + 1, 1) = ...
                    BRResults.permutationPValuePop(brRow);
                resultSource(end + 1, 1) = "PR";
                resultRow(end + 1, 1) = brRow;
            end
        end

        if isempty(rawPValues)
            continue;
        end

        correctedQValues = benjaminiHochbergQValues(rawPValues);

        for jj = 1:length(correctedQValues)
            switch resultSource(jj)
                case "IT"
                    row = resultRow(jj);
                    ITResults.qValueAcrossIT_RT_BR_PR(row) = ...
                        correctedQValues(jj);
                    ITResults.significantFDRAcrossIT_RT_BR_PR(row) = ...
                        correctedQValues(jj) < fdrAlpha;

                case "RT"
                    row = resultRow(jj);
                    RTResults.qValueAcrossIT_RT_BR_PR(row) = ...
                        correctedQValues(jj);
                    RTResults.significantFDRAcrossIT_RT_BR_PR(row) = ...
                        correctedQValues(jj) < fdrAlpha;

                case "BR"
                    row = resultRow(jj);
                    BRResults.qValueBankAcrossIT_RT_BR_PR(row) = ...
                        correctedQValues(jj);
                    BRResults.significantBankFDRAcrossIT_RT_BR_PR(row) = ...
                        correctedQValues(jj) < fdrAlpha;

                case "PR"
                    row = resultRow(jj);
                    BRResults.qValuePopAcrossIT_RT_BR_PR(row) = ...
                        correctedQValues(jj);
                    BRResults.significantPopFDRAcrossIT_RT_BR_PR(row) = ...
                        correctedQValues(jj) < fdrAlpha;
            end
        end

    end

    fprintf('\n============================================================\n');
    fprintf(['BH-FDR correction of permutation p-values finished ' ...
        'within each area across IT, RT, BR, and PR.\n']);
    fprintf('FDR threshold: q < %.3f\n', fdrAlpha);
    fprintf('Significant IT effects: %d\n', ...
        sum(ITResults.significantFDRAcrossIT_RT_BR_PR));
    fprintf('Significant RT effects: %d\n', ...
        sum(RTResults.significantFDRAcrossIT_RT_BR_PR));
    fprintf('Significant BR effects: %d\n', ...
        sum(BRResults.significantBankFDRAcrossIT_RT_BR_PR));
    fprintf('Significant PR effects: %d\n', ...
        sum(BRResults.significantPopFDRAcrossIT_RT_BR_PR));

end

function qValues = benjaminiHochbergQValues(pValues)

    pValues = pValues(:);
    numberOfTests = length(pValues);

    [sortedPValues, sortOrder] = sort(pValues, 'ascend');
    sortedQValues = sortedPValues .* numberOfTests ./ ...
        (1:numberOfTests)';

    % Enforce monotonic BH adjusted p-values without requiring mafdr.
    for ii = numberOfTests - 1:-1:1
        sortedQValues(ii) = min( ...
            sortedQValues(ii), sortedQValues(ii + 1));
    end

    sortedQValues = min(max(sortedQValues, 0), 1);

    qValues = NaN(numberOfTests, 1);
    qValues(sortOrder) = sortedQValues;

end

