function trialRows = makePostIEDWindowRows( ...
    patientID, trialNumber, durationSeconds, IEDoccurrence, ...
    samplingFrequencyHz, balloonColorCode, finalEventObserved, ...
    postIEDWindowSeconds, transitionType)

    if isempty(IEDoccurrence) || size(IEDoccurrence, 2) < 3
        IEDtimes = [];
    else
        validIEDRows = ...
            isfinite(IEDoccurrence(:, 1)) & ...
            isfinite(IEDoccurrence(:, 3)) & ...
            round(IEDoccurrence(:, 1)) == trialNumber & ...
            IEDoccurrence(:, 3) >= 1;

        sampleIndices = double(IEDoccurrence(validIEDRows, 3));
        IEDtimes = sampleIndices ./ samplingFrequencyHz;

        IEDtimes = IEDtimes( ...
            isfinite(IEDtimes) & ...
            IEDtimes > 0 & ...
            IEDtimes < durationSeconds);

        % Keep every IED occurrence, including duplicate times.
        IEDtimes = sort(IEDtimes);
    end

    if isempty(IEDtimes)
        breakTimes = [0; durationSeconds];
    else
        windowEndTimes = min( ...
            IEDtimes + postIEDWindowSeconds, durationSeconds);

        breakTimes = unique([ ...
            0; IEDtimes(:); windowEndTimes(:); durationSeconds], ...
            'sorted');
    end

    breakTimes = breakTimes( ...
        isfinite(breakTimes) & ...
        breakTimes >= 0 & ...
        breakTimes <= durationSeconds);

    breakTimes = unique(breakTimes, 'sorted');

    if length(breakTimes) < 2
        breakTimes = [0; durationSeconds];
    end

    tStart = breakTimes(1:end-1);
    tStop = breakTimes(2:end);

    validIntervals = tStop > tStart;
    tStart = tStart(validIntervals);
    tStop = tStop(validIntervals);

    intervalMidpoint = (tStart + tStop) ./ 2;

    postIED = zeros(length(tStart), 1);
    activeIEDWindowCount = zeros(length(tStart), 1);
    timeSinceMostRecentIED = NaN(length(tStart), 1);

    for kk = 1:length(tStart)

        if isempty(IEDtimes)
            continue;
        end

        activeWindows = ...
            intervalMidpoint(kk) >= IEDtimes & ...
            intervalMidpoint(kk) <= ...
                (IEDtimes + postIEDWindowSeconds);

        activeIEDWindowCount(kk) = sum(activeWindows);
        postIED(kk) = double(any(activeWindows));

        priorIEDtimes = IEDtimes(IEDtimes < intervalMidpoint(kk));

        if ~isempty(priorIEDtimes)
            timeSinceMostRecentIED(kk) = ...
                intervalMidpoint(kk) - max(priorIEDtimes);
        end

    end

    censored = true(length(tStart), 1);
    eventAtStop = false(length(tStart), 1);

    if finalEventObserved
        censored(end) = false;
        eventAtStop(end) = true;
    end

    trialRows = table( ...
        repmat(patientID, length(tStart), 1), ...
        repmat(trialNumber, length(tStart), 1), ...
        tStart, ...
        tStop, ...
        censored, ...
        eventAtStop, ...
        postIED, ...
        activeIEDWindowCount, ...
        timeSinceMostRecentIED, ...
        repmat(balloonColorCode, length(tStart), 1), ...
        repmat(samplingFrequencyHz, length(tStart), 1), ...
        repmat(string(transitionType), length(tStart), 1), ...
        'VariableNames', { ...
            'patientID', ...
            'trialNumber', ...
            'tStart', ...
            'tStop', ...
            'censored', ...
            'eventAtStop', ...
            'postIED', ...
            'activeIEDWindowCount', ...
            'timeSinceMostRecentIED_seconds', ...
            'balloonColorCode', ...
            'samplingFrequencyHz', ...
            'transitionType'});

end

function [X, predictorNames, referenceColorName] = ...
    buildPredictorMatrix(countingProcessData, analysisType)

    % Binary occurrence predictor: 1 anywhere inside at least one active
    % post-IED window and 0 outside all post-IED windows.
    postIEDOccurrence = double(countingProcessData.postIED);

    if analysisType == "BR"
        bankTransition = double( ...
            countingProcessData.transitionType == "bank");
        popTransition = double( ...
            countingProcessData.transitionType == "pop");

        X = [ ...
            postIEDOccurrence .* bankTransition, ...
            postIEDOccurrence .* popTransition];

        predictorNames = [ ...
            "post_area_ied_occurrence_bank_hazard"; ...
            "post_area_ied_occurrence_pop_hazard"];
    else
        X = postIEDOccurrence;
        predictorNames = ...
            "post_area_ied_occurrence_within_selected_window";
    end

    observedColors = unique( ...
        countingProcessData.balloonColorCode, 'sorted');

    observedColors = observedColors(ismember(observedColors, [1 2 3]));

    if isempty(observedColors)
        error('No valid balloon colors were found.');
    end

    if ismember(1, observedColors)
        referenceColor = 1;
    else
        referenceColor = observedColors(1);
    end

    colorNames = ["yellow", "orange", "red"];
    referenceColorName = colorNames(referenceColor);

    comparisonColors = observedColors(observedColors ~= referenceColor);

    for cc = 1:length(comparisonColors)
        colorCode = comparisonColors(cc);
        colorDummy = double( ...
            countingProcessData.balloonColorCode == colorCode);

        if analysisType == "BR"
            X(:, end + 1) = colorDummy .* bankTransition;
            predictorNames(end + 1, 1) = ...
                colorNames(colorCode) + "_vs_" + ...
                colorNames(referenceColor) + "_bank_hazard";

            X(:, end + 1) = colorDummy .* popTransition;
            predictorNames(end + 1, 1) = ...
                colorNames(colorCode) + "_vs_" + ...
                colorNames(referenceColor) + "_pop_hazard";
        else
            X(:, end + 1) = colorDummy;
            predictorNames(end + 1, 1) = ...
                colorNames(colorCode) + "_vs_" + ...
                colorNames(referenceColor);
        end
    end

end

function [robustCovariance, robustSE, robustZ, robustP] = ...
    computeClusterRobustInference(stats, beta, clusterID)

    beta = beta(:);
    nPredictors = length(beta);
    clusterID = clusterID(:);

    uniqueClusters = unique(clusterID(isfinite(clusterID)));
    nClusters = length(uniqueClusters);

    canUseClusterScores = ...
        isfield(stats, 'scores') && ...
        size(stats.scores, 1) == length(clusterID) && ...
        size(stats.scores, 2) == nPredictors;

    if nClusters < 2 || ~canUseClusterScores
        robustCovariance = stats.covb;
        robustSE = stats.se(:);
        robustZ = stats.z(:);
        robustP = stats.p(:);
        return;
    end

    clusterScoreSums = zeros(nClusters, nPredictors);

    for gg = 1:nClusters
        rows = clusterID == uniqueClusters(gg);
        thisClusterScores = stats.scores(rows, :);
        thisClusterScores(~isfinite(thisClusterScores)) = 0;
        clusterScoreSums(gg, :) = sum(thisClusterScores, 1);
    end

    meat = clusterScoreSums' * clusterScoreSums;
    bread = stats.covb;

    robustCovariance = bread * meat * bread;
    robustCovariance = ...
        (nClusters / (nClusters - 1)) .* robustCovariance;

    robustSE = sqrt(max(diag(robustCovariance), 0));

    zeroSERows = robustSE <= 0 | ~isfinite(robustSE);
    robustSE(zeroSERows) = stats.se(zeroSERows);

    robustZ = beta ./ robustSE;
    robustP = 2 .* normcdf(-abs(robustZ), 0, 1);

end

function plotSeparateAreaForestPlots( ...
    ITResults, RTResults, BRResults, ...
    colorIT, colorRT, colorBR, colorPop, markerAlpha, ...
    settings, itOutputPDF, rtOutputPDF, brOutputPDF)

    numberOfITAreas = max(countPlottableAreas(ITResults), 1);
    numberOfRTAreas = max(countPlottableAreas(RTResults), 1);
    numberOfBRAreas = max(countPlottableCompetingAreas(BRResults), 1);

    standardFigureWidth = 1700;
    itFigureHeight = max(650, 48 * numberOfITAreas + 250);
    rtFigureHeight = max(650, 48 * numberOfRTAreas + 250);

    % IT figure
    figIT = figure('Visible', 'off', 'Color', 'w');
    set(figIT, 'Position', ...
        [80 80 standardFigureWidth itFigureHeight]);

    layoutIT = tiledlayout(figIT, 1, 1, ...
        'TileSpacing', 'compact', ...
        'Padding', 'compact');

    axIT = nexttile(layoutIT);
    plotAreaForestPanel( ...
        axIT, ITResults, colorIT, markerAlpha, ...
        "Inflation time", "IT", ...
        settings.postIEDWindowMillisecondsIT);

    exportgraphics(figIT, itOutputPDF, 'ContentType', 'vector');
    close(figIT);

    % RT figure
    figRT = figure('Visible', 'off', 'Color', 'w');
    set(figRT, 'Position', ...
        [80 80 standardFigureWidth rtFigureHeight]);

    layoutRT = tiledlayout(figRT, 1, 1, ...
        'TileSpacing', 'compact', ...
        'Padding', 'compact');

    axRT = nexttile(layoutRT);
    plotAreaForestPanel( ...
        axRT, RTResults, colorRT, markerAlpha, ...
        "Response time", "RT", ...
        settings.postIEDWindowMillisecondsRT);

    exportgraphics(figRT, rtOutputPDF, 'ContentType', 'vector');
    close(figRT);

    % BR figure is deliberately long horizontally.
    brFigureWidth = 3000;
    brFigureHeight = max(600, 42 * numberOfBRAreas + 200);

    figBR = figure('Visible', 'off', 'Color', 'w');
    set(figBR, 'Position', ...
        [80 80 brFigureWidth brFigureHeight]);

    layoutBR = tiledlayout(figBR, 1, 1, ...
        'TileSpacing', 'compact', ...
        'Padding', 'compact');

    axBR = nexttile(layoutBR);
    plotCompetingRiskForestPanel( ...
        axBR, BRResults, colorBR, colorPop, markerAlpha, ...
        settings.postIEDWindowMillisecondsBR);

    exportgraphics(figBR, brOutputPDF, 'ContentType', 'vector');
    close(figBR);

end

function numberOfAreas = countPlottableCompetingAreas(areaResults)

    plotRows = getCompetingForestPlotRows(areaResults);
    numberOfAreas = sum(plotRows);

end

function numberOfAreas = countPlottableAreas(areaResults)

    plotRows = getForestPlotRows(areaResults);
    numberOfAreas = sum(plotRows);

end

function plotAreaForestPanel( ...
    ax, areaResults, panelColor, markerAlpha, ...
    descriptiveTitle, abbreviation, postIEDWindowMilliseconds)

    plotRows = getForestPlotRows(areaResults);
    plotData = areaResults(plotRows, :);

    hold(ax, 'on');

    xline(ax, 0, '--', ...
        'LineWidth', 1.2, ...
        'Color', [0.25 0.25 0.25]);

    if isempty(plotData)
        ax.XLim = [-1 1];
        ax.YLim = [0 1];
        ax.YTick = [];
        text(ax, 0, 0.5, ...
        'No areas with permutation BH-FDR q < 0.05 across IT/RT/BR/PR', ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'middle', ...
            'FontSize', 11);
    else
        plotData = sortrows( ...
            plotData, 'beta_logHazard', 'ascend');
        nAreas = height(plotData);

        for ii = 1:nAreas
            plot(ax, ...
                [plotData.betaCILow(ii), plotData.betaCIHigh(ii)], ...
                [ii, ii], ...
                '-', ...
                'Color', panelColor, ...
                'LineWidth', 1.5);
        end

        scatter(ax, ...
            plotData.beta_logHazard, ...
            (1:nAreas)', ...
            65, ...
            panelColor, ...
            'filled', ...
            'MarkerFaceAlpha', markerAlpha, ...
            'MarkerEdgeColor', 'none');

        ax.YTick = 1:nAreas;

        % Keep the area and both counts in one tick label. Embedded line
        % breaks can be split into separate tick labels by some releases.
        areaTickLabels = strings(nAreas, 1);
        for ii = 1:nAreas
            areaTickLabels(ii) = sprintf( ...
                '%s  |  IED: %d  |  covered: %d', ...
                char(plotData.anatomicalArea(ii)), ...
                plotData.nParticipantsWithIED(ii), ...
                plotData.nParticipantsWithCoverage(ii));
        end
        ax.YTickLabel = cellstr(areaTickLabels);
        ax.YLim = [0.4, nAreas + 0.6];
    end

    ax.TickLabelInterpreter = 'none';
    ax.TickDir = 'out';
    % Set the axes font directly for compatibility across MATLAB releases.
    ax.FontSize = 9;

    xlabel(ax, ...
        'Log hazard ratio: post-IED window versus outside window');

    title(ax, {char(descriptiveTitle), ...
        sprintf('%s - %d-ms post-IED window', ...
            char(abbreviation), postIEDWindowMilliseconds), ...
        'Permutation BH-FDR across IT/RT/BR/PR within area'}, ...
        'FontSize', 12, ...
        'FontWeight', 'bold');

    box(ax, 'off');
    grid(ax, 'off');

end

function plotCompetingRiskForestPanel( ...
    ax, areaResults, bankColor, popColor, markerAlpha, ...
    postIEDWindowMilliseconds)

    plotRows = getCompetingForestPlotRows(areaResults);
    plotData = areaResults(plotRows, :);

    hold(ax, 'on');

    xline(ax, 0, '--', ...
        'LineWidth', 1.2, ...
        'Color', [0.25 0.25 0.25]);

    if isempty(plotData)
        ax.XLim = [-1 1];
        ax.YLim = [0 1];
        ax.YTick = [];
        text(ax, 0, 0.5, ...
        'No BR or PR effects with permutation BH-FDR q < 0.05', ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'middle', ...
            'FontSize', 11);
    else
        plotData = sortrows( ...
            plotData, 'beta_logHazard', 'ascend');
        nAreas = height(plotData);

        bankY = (1:nAreas)' + 0.12;
        popY = (1:nAreas)' - 0.12;

        allConfidenceValues = [ ...
            plotData.betaCILow; ...
            plotData.betaCIHigh; ...
            plotData.betaPopCILow; ...
            plotData.betaPopCIHigh; ...
            0];

        allConfidenceValues = ...
            allConfidenceValues(isfinite(allConfidenceValues));

        minimumX = min(allConfidenceValues);
        maximumX = max(allConfidenceValues);
        xRange = maximumX - minimumX;

        if ~isfinite(xRange) || xRange <= 0
            xRange = 1;
        end

        starOffset = 0.015 * xRange;
        leftPadding = 0.06 * xRange;
        rightPadding = 0.20 * xRange;

        for ii = 1:nAreas
            plot(ax, ...
                [plotData.betaCILow(ii), plotData.betaCIHigh(ii)], ...
                [bankY(ii), bankY(ii)], ...
                '-', ...
                'Color', bankColor, ...
                'LineWidth', 1.5);

            plot(ax, ...
                [plotData.betaPopCILow(ii), ...
                 plotData.betaPopCIHigh(ii)], ...
                [popY(ii), popY(ii)], ...
                '-', ...
                'Color', popColor, ...
                'LineWidth', 1.5);
        end

        bankPoint = scatter(ax, ...
            plotData.beta_logHazard, ...
            bankY, ...
            65, ...
            bankColor, ...
            'o', ...
            'filled', ...
            'MarkerFaceAlpha', markerAlpha, ...
            'MarkerEdgeColor', 'none');

        popPoint = scatter(ax, ...
            plotData.betaPop_logHazard, ...
            popY, ...
            65, ...
            popColor, ...
            'd', ...
            'filled', ...
            'MarkerFaceAlpha', markerAlpha, ...
            'MarkerEdgeColor', 'none');

        % A star beside a point means that the BR or PR coefficient
        % survives BH-FDR across IT, RT, BR, and PR within this area.
        for ii = 1:nAreas

            if plotData.significantBankFDRAcrossIT_RT_BR_PR(ii)
                text(ax, ...
                    plotData.beta_logHazard(ii) + starOffset, ...
                    bankY(ii), ...
                    '*', ...
                    'Color', bankColor, ...
                    'FontSize', 14, ...
                    'FontWeight', 'bold', ...
                    'HorizontalAlignment', 'left', ...
                    'VerticalAlignment', 'middle');
            end

            if plotData.significantPopFDRAcrossIT_RT_BR_PR(ii)
                text(ax, ...
                    plotData.betaPop_logHazard(ii) + starOffset, ...
                    popY(ii), ...
                    '*', ...
                    'Color', popColor, ...
                    'FontSize', 14, ...
                    'FontWeight', 'bold', ...
                    'HorizontalAlignment', 'left', ...
                    'VerticalAlignment', 'middle');
            end

        end

        ax.YTick = 1:nAreas;

        areaTickLabels = strings(nAreas, 1);
        for ii = 1:nAreas
            areaTickLabels(ii) = sprintf( ...
                '%s  |  IED: %d  |  covered: %d', ...
                char(plotData.anatomicalArea(ii)), ...
                plotData.nParticipantsWithIED(ii), ...
                plotData.nParticipantsWithCoverage(ii));
        end

        ax.YTickLabel = cellstr(areaTickLabels);
        ax.YLim = [0.4, nAreas + 0.6];
        ax.XLim = [ ...
            minimumX - leftPadding, ...
            maximumX + rightPadding];

        legend(ax, [bankPoint, popPoint], ...
            {'bank hazard', 'pop hazard'}, ...
            'Location', 'best', ...
            'Box', 'off');
    end

    ax.TickLabelInterpreter = 'none';
    ax.TickDir = 'out';
    ax.FontSize = 9;

    xlabel(ax, ...
        'Log hazard ratio: post-IED window versus outside window');

    title(ax, { ...
        'Bank and pop competing transitions', ...
        sprintf('BR - %d-ms post-IED window', ...
            postIEDWindowMilliseconds), ...
        'Both coefficients come from one combined Cox model', ...
        'Permutation BH-FDR across IT/RT/BR/PR within area', ...
        '* = q < 0.05'}, ...
        'FontSize', 12, ...
        'FontWeight', 'bold');

    box(ax, 'off');
    grid(ax, 'off');

end

function plotRows = getCompetingForestPlotRows(areaResults)

    anySignificantEffect = ...
        areaResults.significantBankFDRAcrossIT_RT_BR_PR | ...
        areaResults.significantPopFDRAcrossIT_RT_BR_PR;

    plotRows = ...
        ~isExcludedAreaLabel(areaResults.anatomicalArea) & ...
        areaResults.status == "fitted" & ...
        anySignificantEffect & ...
        isfinite(areaResults.beta_logHazard) & ...
        isfinite(areaResults.betaCILow) & ...
        isfinite(areaResults.betaCIHigh) & ...
        isfinite(areaResults.betaPop_logHazard) & ...
        isfinite(areaResults.betaPopCILow) & ...
        isfinite(areaResults.betaPopCIHigh);

end

function plotRows = getForestPlotRows(areaResults)

    plotRows = ...
        ~isExcludedAreaLabel(areaResults.anatomicalArea) & ...
        areaResults.status == "fitted" & ...
        areaResults.significantFDRAcrossIT_RT_BR_PR & ...
        isfinite(areaResults.beta_logHazard) & ...
        isfinite(areaResults.betaCILow) & ...
        isfinite(areaResults.betaCIHigh);

end
